DROP TABLE IF EXISTS compat_orders;
DROP TABLE IF EXISTS compat_users;

CREATE TABLE compat_users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL,
  email text NOT NULL,
  profile jsonb NOT NULL,
  created_at timestamp NOT NULL DEFAULT now(),
  CONSTRAINT compat_users_email_key UNIQUE (email)
);

CREATE INDEX compat_users_username_idx ON compat_users (username);

CREATE TABLE compat_orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES compat_users(id),
  order_no text NOT NULL UNIQUE,
  amount numeric(12,2) NOT NULL,
  attrs json NOT NULL,
  created_at timestamp NOT NULL DEFAULT now()
);

CREATE INDEX compat_orders_user_id_idx ON compat_orders (user_id);

